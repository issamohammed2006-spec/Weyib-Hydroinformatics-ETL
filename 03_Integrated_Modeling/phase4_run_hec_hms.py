import pandas as pd
from hms_commander import init_hms_project, HmsCmdr, HmsResults
import os

def run_automated_hms():
    print("Starting Phase 4: Automated HEC-HMS Execution...")
    
    # ==========================================
    # CONFIGURATION - UPDATE THESE PATHS!
    # ==========================================
    # Path to your HEC-HMS project file
    HMS_PROJECT = r"D:\Thesis\Weyib2\Weyib2.hms" 
    
    # The name of the Simulation Run inside HEC-HMS (e.g., 'Run_100yr')
    SIMULATION_NAME = "Run_100yr" 
    
    if not os.path.exists(HMS_PROJECT):
        print(f"ERROR: HEC-HMS project not found at {HMS_PROJECT}")
        return

    # 1. Initialize the Project
    print(f"Initializing HEC-HMS Project: {HMS_PROJECT}...")
    hms = init_hms_project(HMS_PROJECT)

    # 2. Update the Meteorologic Model with your Design Storm
    # (Optional: If you already set up your Met Model in HEC-HMS to read the 100yr_Design.csv, you can skip this)
    print("Updating rainfall data from Design Storm...")
    try:
        # Load the 100-year design storm we generated in Phase 3
        design_storm_path = "data/processed/100yr_design_storm_hyetograph.csv"
        storm_df = pd.read_csv(design_storm_path)
        
        # Example of how you could programmatically update the HEC-HMS Met Model
        # (Requires the exact gage name and column mapping based on your specific HMS setup)
        # hms.met_df.update_manual_precipitation("Subbasin-1", storm_df['Subbasin-1'].values)
        
    except Exception as e:
        print(f"Warning: Could not update Met model automatically. Ensure HEC-HMS is pre-configured. Error: {e}")

    # 3. Execute the Simulation
    print(f"\nExecuting HEC-HMS Simulation: {SIMULATION_NAME}...")
    try:
        # HmsCmdr.compute_run triggers the HEC-HMS engine
        success = HmsCmdr.compute_run(SIMULATION_NAME)
        
        if success:
            print("✅ HEC-HMS Simulation Completed Successfully!")
        else:
            print("❌ Simulation failed. Check the HEC-HMS log files.")
            return
            
    except Exception as e:
        print(f"Execution Error: {e}")
        return

    # 4. Extract the Peak Flow Results
    print("\nExtracting Results...")
    dss_file_path = HMS_PROJECT.replace('.hms', '.dss')
    
    try:
        # HmsResults automatically reads the DSS file generated by HEC-HMS
        # We look for the Outlet Junction (e.g., 'Sink-1' or 'Junction-1')
        results = HmsResults(dss_file_path)
        
        # Note: The exact pathname depends on your basin model name
        # This is a generic example. You may need to adjust the pathname to match your specific outlet.
        flow_path = "/A=Weyib2/B=Sink-1/C=FLOW/D=01JAN2000/E=1HOUR/F=OBS/"
        
        peak_flow = results.get_peak_flow(flow_path)
        
        if peak_flow:
            print(f"🎯 AUTOMATED RESULT: Peak Flow for 100-Year Event = {peak_flow:.2f} m³/s")
            
            # Save this for HEC-RAS Phase
            with open("data/processed/automated_peak_flow.txt", "w") as f:
                f.write(str(peak_flow))
        else:
            print("Could not extract peak flow. Please check the DSS pathname.")
            
    except Exception as e:
        print(f"Error extracting results: {e}")

if __name__ == "__main__":
    run_automated_hms()